# A6 pre-push gate installer (roadmap 2026-10-14).
# Usage:
#   business repo root:  powershell -NoProfile -ExecutionPolicy Bypass -File .agent-kb\scripts\install-gate.ps1
#   Agent-KB itself:     powershell -NoProfile -ExecutionPolicy Bypass -File scripts\install-gate.ps1
#   other repo path:     ... -File <this file> -RepoRoot d:\path\to\repo
# Idempotent: re-run to refresh gate body + launcher after updating the master copy.
# Existing foreign pre-push (e.g. git-lfs) is renamed to pre-push.chain and chained by the launcher.
param([string]$RepoRoot = (Get-Location).Path)
$ErrorActionPreference = 'Stop'

# 1. locate gate master: Agent-KB scripts/ or business repo submodule .agent-kb/scripts/
$candidates = @(
    (Join-Path $PSScriptRoot 'pre-push-gate.sh'),
    (Join-Path $RepoRoot '.agent-kb\scripts\pre-push-gate.sh')
)
$gateSrc = $candidates | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $gateSrc) { throw 'pre-push-gate.sh not found (Agent-KB scripts/ or .agent-kb/scripts/)' }

# 2. resolve hooks dir (git-path works for worktree/submodule; may be relative to repo root)
$hooksDir = (git -C $RepoRoot rev-parse --git-path hooks).Trim()
if (-not [IO.Path]::IsPathRooted($hooksDir)) {
    $repoTop = (git -C $RepoRoot rev-parse --show-toplevel).Trim()
    $hooksDir = Join-Path $repoTop ($hooksDir -replace '/', '\')
}
New-Item -ItemType Directory -Force -Path $hooksDir | Out-Null

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$toLf = { param($s) $s -replace "`r`n", "`n" -replace "`r", "`n" }

# 3. copy gate body (LF, no BOM -- sh chokes on BOM/CRLF)
$text = & $toLf ([IO.File]::ReadAllText($gateSrc))
[IO.File]::WriteAllText((Join-Path $hooksDir 'pre-push-gate.sh'), $text, $utf8NoBom)

# 4. back up foreign pre-push once (skip our own launcher on re-install)
$launcherMarker = 'pre-push-gate.sh'
$launcherPath = Join-Path $hooksDir 'pre-push'
if (Test-Path $launcherPath) {
    $existing = [IO.File]::ReadAllText($launcherPath)
    if ($existing -notmatch [regex]::Escape($launcherMarker)) {
        Move-Item $launcherPath (Join-Path $hooksDir 'pre-push.chain') -Force
        Write-Host "installed-gate: previous pre-push moved to pre-push.chain (now chained)"
    }
}

# 5. write launcher (chained: pre-push.chain -> pre-push-gate.sh; stdin ref lines fed to both)
$launcher = @'
#!/bin/sh
# A6 pre-push launcher (generated by install-gate.ps1; edit master in Agent-KB/scripts/pre-push-gate.sh).
# Ref lines are buffered once and fed to both the chained foreign hook (e.g. git-lfs) and the gate.
dir=$(dirname "$0")
input=$(cat)
if [ -f "$dir/pre-push.chain" ]; then
    printf '%s\n' "$input" | sh "$dir/pre-push.chain" "$@" || exit $?
fi
printf '%s\n' "$input" | sh "$dir/pre-push-gate.sh" "$@"
'@
[IO.File]::WriteAllText($launcherPath, (& $toLf $launcher), $utf8NoBom)

Write-Host "installed-gate: OK -> $hooksDir"
Write-Host "  gate body : pre-push-gate.sh (master: $gateSrc)"
Write-Host "  launcher  : pre-push"
Write-Host "  emergency skip: `$env:PREPUSH_SKIP='1'; git push ..."
